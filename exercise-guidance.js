window.exerciseGuidance=function(exercise){
  const text=String(exercise);
  const afterFirstSentence=text.split('.').slice(1).join('.').trim();
  if(afterFirstSentence.length>12)return text;
  const rules=[
    [/жим.*(л[её]жа|наклон|тренаж)/i,'Лопатки сведены, стопы устойчиво; опускайте вес под контролем и выжимайте без рывка.'],
    [/жим.*сидя/i,'Спина опирается на скамью, живот напряжён; не прогибайтесь в пояснице.'],
    [/жим.*опор/i,'Корпус держите прямой, локти направляйте примерно под 45° к корпусу.'],
    [/тяга.*(верхн|вертикал|нейтраль)/i,'Сначала опустите плечи, затем тяните рукоять к верхней части груди; не раскачивайтесь.'],
    [/тяга.*(горизонт|пояс|гантел)/i,'Тяните локоть к тазу или рукоять к животу, в конце движения сведите лопатки.'],
    [/тяга к лицу/i,'Тяните рукоять к уровню глаз, локти разводите в стороны, шею не тяните вперёд.'],
    [/румынск/i,'Отводите таз назад, спина остаётся ровной, вес держите близко к ногам.'],
    [/(присед|гоблет)/i,'Стопы устойчиво, колени движутся по линии носков; опускайтесь только до комфортной глубины.'],
    [/жим ногами/i,'Поясница остаётся прижата к спинке, колени не выпрямляйте до жёсткого упора.'],
    [/ягодичн.*мост/i,'Давите пятками в пол, вверху сожмите ягодицы; поясницу не переразгибайте.'],
    [/(сгибание ног|разгибание ног)/i,'Двигайтесь плавно, без рывка; не используйте вес, при котором теряется контроль.'],
    [/отведение бедра/i,'Корпус сохраняйте неподвижным, отводите ногу медленно и без разворота таза.'],
    [/разгибание бедра/i,'Напрягайте ягодицу, не прогибайте поясницу и не раскачивайте корпус.'],
    [/подъ[её]м на носки|икры/i,'Поднимайтесь плавно, сделайте короткую паузу вверху и медленно опуститесь.'],
    [/планк/i,'Локти или ладони под плечами, живот подтянут, поясница не провисает.'],
    [/dead bug/i,'Поясница мягко прижата к полу; вытягивайте противоположные руку и ногу медленно.'],
    [/bird-dog/i,'На четвереньках вытягивайте противоположные руку и ногу, не разворачивая таз.'],
    [/гиперэкстенз/i,'Поднимайтесь до прямой линии корпуса, не запрокидывайтесь в пояснице.'],
    [/разведен|обратн.*развед/i,'Поднимайте вес без маха, плечи не поднимайте к ушам.'],
    [/сгибание рук/i,'Локти оставьте возле корпуса, не раскачивайте туловище.'],
    [/разгибание рук/i,'Зафиксируйте локти, разгибайте руки полностью без рывка.'],
    [/фермер|перенос веса/i,'Корпус высокий, плечи опущены, идите небольшими устойчивыми шагами.'],
    [/шаг на низк/i,'Держитесь за опору, поднимайтесь через пятку; при боли в колене остановитесь и замените упражнение.'],
    [/ходьб/i,'Выберите спокойный темп, при котором можно говорить полными фразами.']
  ];
  const found=rules.find(([pattern])=>pattern.test(text));
  return `${text.replace(/\.$/,'')}. ${found?found[1]:'Двигайтесь медленно и контролируемо; сохраняйте ровное дыхание и прекращайте упражнение при боли.'}`;
};

const beforeExerciseGuidanceApp=appF;
appF=function(id,month=0){
  beforeExerciseGuidanceApp(id,month);
  document.querySelectorAll(`#${id} .sa-session li`).forEach(item=>{
    if(!item.dataset.exercise)item.textContent=window.exerciseGuidance(item.textContent);
  });
};
appF('alex');
appF('elena');
